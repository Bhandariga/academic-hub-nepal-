CREATE TABLE IF NOT EXISTS successful_students (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL, photo VARCHAR(255) DEFAULT NULL,
 program VARCHAR(20) NOT NULL, campus VARCHAR(150) NOT NULL, achievement VARCHAR(200) NOT NULL,
 story TEXT NOT NULL, graduation_year SMALLINT NOT NULL, display_order INT NOT NULL DEFAULT 0,
 status TINYINT(1) NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_success_visible (status, display_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS colleges (
 id INT AUTO_INCREMENT PRIMARY KEY, college_name VARCHAR(150) NOT NULL, photo VARCHAR(255) DEFAULT NULL,
 location VARCHAR(150) NOT NULL, university VARCHAR(150) NOT NULL, programs VARCHAR(255) NOT NULL,
 website VARCHAR(255) DEFAULT NULL, description TEXT NOT NULL, status TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_college_visible(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS society_gallery (
 id INT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(150) NOT NULL, image VARCHAR(255) DEFAULT NULL,
 category VARCHAR(60) NOT NULL, description TEXT NOT NULL, status TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, INDEX idx_gallery_visible(status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS media_assets (
 id INT AUTO_INCREMENT PRIMARY KEY, filename VARCHAR(255) NOT NULL UNIQUE, alt_text VARCHAR(200) NOT NULL,
 category VARCHAR(40) NOT NULL, width INT NOT NULL, height INT NOT NULL, file_size INT NOT NULL,
 uploaded_by INT DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
